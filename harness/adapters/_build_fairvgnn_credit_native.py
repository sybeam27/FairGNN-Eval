def build() -> str:
    src = open(SHARED).read().splitlines(keepends=True)
    s = next(i for i, l in enumerate(src)
             if l.startswith("    def run(self, data, args, trajectory=None):"))
    e = next(i for i, l in enumerate(src)
             if l.startswith("    def inference_modules(self):"))
    body = textwrap.dedent("".join(src[s:e]).rstrip() + "\n")
    for what, old, new in EDITS:
        n = body.count(old)
        if n != 1:
            raise SystemExit(f"{what}: anchor found {n} times in the shared run()")
        body = body.replace(old, new)
    return HEADER + body + FOOTER


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true",
                    help="verify the committed adapter equals a fresh build")
    a = ap.parse_args()
    text = build()
    if a.check:
        same = os.path.exists(TARGET) and open(TARGET).read() == text
        print("adapter matches a fresh build" if same
              else "adapter DIFFERS from a fresh build")
        return 0 if same else 1
    open(TARGET, "w").write(text)
    print(f"wrote {TARGET}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
