"""Native FairVGNN/credit adapter: a faithful mirror of the official
fairvgnn_credit.py training loop (FairVGNN 938f2e8), per X19.

GENERATED by harness/adapters/_build_fairvgnn_credit_native.py from the local
`algorithms/FairVGNN.py` `FairVGNN.run()`, with exactly the verified credit
differences applied and nothing else:

    [credit 1] discriminator phase: encoder.eval() instead of encoder.train()
    [credit 2] discriminator phase: no optimizer_e.zero_grad()
    [credit 3] discriminator phase: no optimizer_e.step()
    [credit 4] inside `if args.weight_clip == 'yes'`, after
               encoder.clip_parameters(weights): classifier.clip_parameters()

plus one plumbing line, `args.clip_c = self._clip_c`, because the official
argparse supplies --clip_c (default 1) and the local args_class does not.

Neither the shared wrapper nor the upstream source is edited. The function
below is compiled here and then rebound to the *live* `algorithms.FairVGNN`
module globals, so every module-level name it uses -- `evaluate_ged3`,
`seed_everything`, `tqdm`, the encoder/classifier classes -- resolves exactly
as in the shared wrapper. The harness's own run-time wrappers (the RNG-bundle
capture around evaluate_ged3) therefore apply unchanged.

M0 (f_mask = no, weight_clip = no) switches classifier clipping off together
with encoder weight clipping, because the official script places it inside the
weight_clip block. The discriminator-phase encoder freeze is not a flag and is
on in both arms, as in the official script.
"""
